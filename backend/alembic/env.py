# 5) Autogenerate behaviour
# ---------------------------------------------------------------------------
# Tables/objects that Alembic must never touch (extensions, PostGIS, etc.)
# TODO: add your own names if needed
EXCLUDED_TABLES: set[str] = {"spatial_ref_sys"}

# compare_server_default only detects changes in DB-side defaults, i.e.
# Column(..., server_default=...). It does NOT see Python-side defaults such as
# Column(..., default=True) because those never exist in the database schema.
# Tip: use sa.true() / sa.false() / sa.func.now() / sa.text("...") as server_default
# so the rendered value matches what PostgreSQL reports (fewer false positives).
# Always review autogenerated migrations; set to False if server defaults get noisy.
COMPARE_SERVER_DEFAULT = True


def include_object(obj, name, type_, reflected, compare_to) -> bool:
    if type_ == "table" and name in EXCLUDED_TABLES:
        return False
    return True


# By default, `revision --autogenerate` fails (no file is
# written) when risky operations are detected. Set ALEMBIC_FAIL_ON_DESTRUCTIVE=0
# only when you deliberately want to review and manually edit such a revision.
FAIL_ON_DESTRUCTIVE = os.getenv("ALEMBIC_FAIL_ON_DESTRUCTIVE", "1") == "1"


def _flatten_ops(op_list):
    """Yield (table_name, op) for top-level ops and ops nested in ModifyTableOps."""
    for op in op_list:
        if isinstance(op, ops.ModifyTableOps):
            for sub in op.ops:
                yield op.table_name, sub
        else:
            yield getattr(op, "table_name", None), op


def _destructive_operations(upgrade_ops) -> list[str]:
    """Describe risky operations found in an autogenerated script.

    Covers: drop table/column/index/constraint, column type changes, and
    NOT NULL changes. It cannot inspect data migrations, and Alembic cannot detect
    renames (a rename shows up as drop + create, which loses data).
    """
    found: list[str] = []
    for table, op in _flatten_ops(upgrade_ops.ops):
        if isinstance(op, ops.DropTableOp):
            found.append(f"drop_table: {op.table_name}")
        elif isinstance(op, ops.DropColumnOp):
            found.append(f"drop_column: {table}.{op.column_name}")
        elif isinstance(op, ops.DropConstraintOp):
            found.append(f"drop_constraint: {table}.{op.constraint_name}")
        elif isinstance(op, ops.DropIndexOp):
            found.append(f"drop_index: {op.index_name}")
        elif isinstance(op, ops.AlterColumnOp):
            if op.modify_type is not None:
                found.append(f"alter_column type: {table}.{op.column_name}")
            if op.modify_nullable is False:
                found.append(f"alter_column SET NOT NULL: {table}.{op.column_name}")
    return found


def process_revision_directives(context_, revision, directives) -> None:
    """Skip empty migrations and flag destructive operations."""
    if not getattr(config.cmd_opts, "autogenerate", False):
        return
    if not directives:
        return

    if all(script.upgrade_ops.is_empty() for script in directives):
        directives[:] = []
        logger.info("No changes detected; no migration file was created.")
        return

    risky = [
        item for script in directives for item in _destructive_operations(script.upgrade_ops)
    ]
    for item in risky:
        logger.warning(
            "Risky operation in generated migration -> %s "
            "(if this is a rename, use op.rename_table / op.alter_column instead).",
            item,
        )
    if risky and FAIL_ON_DESTRUCTIVE:
        raise RuntimeError(
            f"{len(risky)} risky operation(s) detected and ALEMBIC_FAIL_ON_DESTRUCTIVE=1; "
            "no migration file was written."
        )


def common_context_options() -> dict:
    return {
        "target_metadata": target_metadata,
        "compare_type": True,  # detect column type changes
        "compare_server_default": COMPARE_SERVER_DEFAULT,
        "include_object": include_object,
        "process_revision_directives": process_revision_directives,
        # TODO: uncomment if you keep tables in a non-default schema
        # "include_schemas": True,
        # "version_table_schema": "public",
    }


# ---------------------------------------------------------------------------
# 6) Session-level advisory lock (PostgreSQL only)
# ---------------------------------------------------------------------------
# Advisory locks are scoped to a single database, so different environments
# (separate databases) never block each other. The name only needs to be unique
# among projects that share the SAME database; all instances of this project
# must use the same name.
# TODO: change the name if another project shares this database.
MIGRATION_LOCK_NAME = "fanavaran_farda_sirjan:alembic_migrations"
LOCK_POLL_INTERVAL_SECONDS = 1.0

# Read-only commands that normally do not need the lock. Revision can opt in.
LOCK_FREE_COMMANDS = {"revision", "check", "current"}

# Set to True to also take the lock for `revision --autogenerate`, so it waits for any
# running migration instead of comparing against a half-migrated database.
# (Prefer autogenerate against a dev/test database, not a live one.)
LOCK_FOR_AUTOGENERATE = True


def _lock_key(name: str) -> int:
    """Deterministic signed 64-bit integer (pg_advisory_lock takes a bigint)."""
    digest = hashlib.sha256(name.encode("utf-8")).digest()[:8]
    return int.from_bytes(digest, "big", signed=True)


LOCK_KEY = _lock_key(MIGRATION_LOCK_NAME)


def _read_lock_timeout() -> int:
    raw = os.getenv("MIGRATION_LOCK_TIMEOUT_SECONDS", "300")
    try:
        value = int(raw)
    except ValueError:
        raise RuntimeError(
            f"MIGRATION_LOCK_TIMEOUT_SECONDS must be an integer, got {raw!r}."
        ) from None
    if value <= 0:
        raise RuntimeError(
            f"MIGRATION_LOCK_TIMEOUT_SECONDS must be greater than 0, got {value}."
        )
    return value


def _current_command_name() -> str | None:
    """Name of the running Alembic CLI command (None when used programmatically)."""
    cmd = getattr(config.cmd_opts, "cmd", None)
    if cmd:
        return getattr(cmd[0], "__name__", None)
    return None


def should_use_lock() -> bool:
    name = _current_command_name()
    if name == "revision" and LOCK_FOR_AUTOGENERATE:
        return True
    return name not in LOCK_FREE_COMMANDS


def acquire_migration_lock(connection: Connection) -> None:
    """Block (with timeout) until we own the session-level advisory lock.

    The lock belongs to this PostgreSQL session, so it stays held across commits
    and non-transactional operations for as long as `connection` is open.
    """
    timeout = _read_lock_timeout()
    deadline = time.monotonic() + timeout
    waiting_logged = False

    while True:
        acquired = connection.execute(
            text("SELECT pg_try_advisory_lock(:key)"), {"key": LOCK_KEY}
        ).scalar()
        # End the autobegun transaction right away (the session lock survives it).
        # This is REQUIRED: if a transaction is already open when Alembic's
        # begin_transaction() runs, Alembic treats it as external and never commits.
        connection.commit()

        if acquired:
            return

        if not waiting_logged:
            logger.info("Another migration is running; waiting for the lock...")
            waiting_logged = True

        if time.monotonic() >= deadline:
            raise RuntimeError(
                f"Could not acquire the migration lock within {timeout}s. "
                "Another migration may be stuck."
            )
        time.sleep(LOCK_POLL_INTERVAL_SECONDS)


def release_migration_lock(connection: Connection) -> None:
    """Release the lock without masking the original migration error (if any).

    If the explicit unlock fails, the physical connection is invalidated (closed),
    which normally closes the DBAPI connection and releases its session lock.
    """
    try:
        if connection.in_transaction():
            connection.rollback()
        released = connection.execute(
            text("SELECT pg_advisory_unlock(:key)"), {"key": LOCK_KEY}
        ).scalar()
        connection.commit()
        if not released:
            logger.warning("Advisory lock was not held by this session at release time.")
    except Exception:  # noqa: BLE001
        logger.warning(
            "Could not explicitly release the advisory lock; "
            "closing the connection so PostgreSQL releases it.",
            exc_info=True,
        )
        try:
            connection.invalidate()
        except Exception:  # noqa: BLE001
            logger.error(
                "Could not close the connection either; the lock is released "
                "when the process exits or the session is terminated.",
                exc_info=True,
            )


# ---------------------------------------------------------------------------
# 7) Offline mode (generates SQL without connecting)
# ---------------------------------------------------------------------------
def run_migrations_offline() -> None:
    url = get_database_url()
    detect_async(url)  # validate backend/driver early

    context.configure(
        url=url,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        **common_context_options(),
    )

    with context.begin_transaction():
        context.run_migrations()


# ---------------------------------------------------------------------------
# 8) Online mode
# ---------------------------------------------------------------------------
def do_run_migrations(connection: Connection) -> None:
    """Runs on ONE connection: lock -> migrate -> unlock (all the same session)."""
    use_lock = should_use_lock()
    if use_lock:
        acquire_migration_lock(connection)
    try:
        context.configure(connection=connection, **common_context_options())
        with context.begin_transaction():
            context.run_migrations()
    finally:
        if use_lock:
            release_migration_lock(connection)


async def run_async_migrations(configuration: dict) -> None:
    connectable = async_engine_from_config(
        configuration,
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,  # exactly one connection, closed at the end
    )
    try:
        async with connectable.connect() as connection:
            await connection.run_sync(do_run_migrations)
    finally:
        await connectable.dispose()


def run_migrations_online() -> None:
    url = get_database_url()
    use_async = detect_async(url)

    # Build the config dict directly (don't use config.set_main_option):
    # passwords containing '%' would break ConfigParser interpolation.
    configuration = dict(config.get_section(config.config_ini_section, {}) or {})
    configuration["sqlalchemy.url"] = url

    if use_async:
        try:
            asyncio.get_running_loop()
        except RuntimeError:
            pass  # no running loop: normal CLI usage
        else:
            raise RuntimeError(
                "Alembic was started inside a running event loop. Run migrations "
                "from the CLI (`alembic upgrade head`) or in a separate thread/process."
            )
        asyncio.run(run_async_migrations(configuration))
        return

    connectable = engine_from_config(
        configuration,
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,  # exactly one connection, closed at the end
    )
    try:
        with connectable.connect() as connection:
            do_run_migrations(connection)
    finally:
        connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()