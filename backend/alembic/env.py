"""Alembic environment for FastAPI + SQLAlchemy 2.x + PostgreSQL.

Requirements: SQLAlchemy >= 2.0, Alembic >= 1.12, PostgreSQL only.

Supported drivers (explicit, anything else fails with a clear error):
- postgresql+asyncpg                       -> async engine
- postgresql+psycopg2 / postgresql+psycopg -> sync engine
- postgresql (no driver)                   -> sync engine (SQLAlchemy default: psycopg2)

Design notes:
- The DB URL comes from ONE source only: app settings (same URL the app uses).
- All models are imported (app.models), with required-table checks.
  Review every autogenerated revision before running it.
- A session-level advisory lock protects upgrade/downgrade and, by default,
  autogenerate against concurrent migrations using the same lock.
- Run migrations from the CLI / deploy step (e.g. `alembic upgrade head`), not from
  inside the FastAPI app startup.
- Do NOT stamp an existing database unless its schema matches the baseline revision.
"""

