# ---------------------------------------------------------------------------
# 4) Database URL (single source: app settings) + explicit driver validation
# ---------------------------------------------------------------------------
ASYNC_DRIVERS = {"asyncpg"}
SYNC_DRIVERS = {"psycopg2", "psycopg"}
DEFAULT_DRIVER = "psycopg2"  # SQLAlchemy's default for plain "postgresql://"


def _to_url_string(value) -> str:
    """Convert whatever the settings hold into a URL string WITH the real password."""
    if isinstance(value, URL):  # SQLAlchemy URL: str() would mask the password
        return value.render_as_string(hide_password=False)
    if hasattr(value, "get_secret_value"):  # pydantic SecretStr
        return value.get_secret_value()
    return str(value)  # str or pydantic AnyUrl/PostgresDsn


def get_database_url() -> str:
    raw = getattr(settings, "DATABASE_URL", None)
    url = _to_url_string(raw).strip() if raw else ""

    if not url:
        raise RuntimeError(
            "settings.DATABASE_URL is empty or missing. Alembic uses the same "
            "database URL as the application; there is no fallback."
        )

    # Heroku/Render style URLs use the legacy 'postgres://' scheme
    if url.startswith("postgres://"):
        url = url.replace("postgres://", "postgresql://", 1)

    return url


def detect_async(url: str) -> bool:
    """Return True for async drivers, False for sync ones; reject everything else.

    Note: we pass the ORIGINAL url string to the engine, never str(parsed_url),
    because SQLAlchemy 2.x masks the password (***) when rendering a URL object.
    """
    drivername = make_url(url).drivername
    backend, _, driver = drivername.partition("+")
    driver = driver or DEFAULT_DRIVER

    if backend != "postgresql":
        raise RuntimeError(
            f"Unsupported database backend '{backend}'. This env.py supports PostgreSQL only."
        )
    if driver in ASYNC_DRIVERS:
        return True
    if driver in SYNC_DRIVERS:
        return False

    supported = sorted(ASYNC_DRIVERS | SYNC_DRIVERS)
    raise RuntimeError(
        f"Unsupported PostgreSQL driver '{driver}'. Supported drivers: {supported}."
    )


